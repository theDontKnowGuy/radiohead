#!/usr/bin/env python3
"""Independent sin() generator; no radio or existing experiment imports."""
import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RATE, PERIOD, FADE, LENGTH = 44100, 882, 2205, 220500

def tables():
    out = {}
    for level in (-30, -24):
        for name, frequencies in (("250", (250,)), ("1000", (1000,)), ("mix", (250, 1000))):
            raw = [sum(math.sin(2 * math.pi * f * n / RATE) for f in frequencies) for n in range(PERIOD)]
            gain = 32768 * 10 ** (level / 20) / max(abs(v) for v in raw)
            def quant(n, envelope=1):
                v = raw[n % PERIOD] * gain * envelope
                return math.floor(v + .5) if v >= 0 else math.ceil(v - .5)
            tag = f"pcm_{abs(level)}_{name}"
            out[tag + "_period"] = [quant(n) for n in range(PERIOD)]
            out[tag + "_in"] = [quant(n, .5 - .5 * math.cos(math.pi * n / (FADE - 1))) for n in range(FADE)]
            out[tag + "_out"] = [quant(LENGTH - FADE + n, .5 + .5 * math.cos(math.pi * n / (FADE - 1))) for n in range(FADE)]
    return out

def content():
    text = ["/* Generated by tools/generate_pcm.py. Signed PCM, not runtime synthesis. */",
            "#ifndef TONE_PCM_TABLES_H", "#define TONE_PCM_TABLES_H", "#include <stdint.h>",
            f"#define PCM_PERIOD_FRAMES {PERIOD}u", f"#define PCM_FADE_FRAMES {FADE}u",
            "struct tone_pcm { const int16_t *period, *fade_in, *fade_out; };"]
    for name, values in tables().items():
        text.append(f"static const int16_t {name}[{len(values)}] = {{")
        text.extend("    " + ", ".join(map(str, values[n:n+16])) + "," for n in range(0,len(values),16))
        text.append("};")
    text.append("static const struct tone_pcm tone_pcm[6] = {")
    for level in (30,24):
        for name in ("250","1000","mix"):
            tag=f"pcm_{level}_{name}"
            text.append(f"    {{{tag}_period, {tag}_in, {tag}_out}},")
    text.extend(["};", "#endif", ""])
    return "\n".join(text)

if __name__ == "__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check",action="store_true")
    args=p.parse_args()
    path=ROOT/"src/pcm_tables.h"
    if args.check:
        assert path.read_text() == content(), "PCM tables differ; regenerate and review"
        print("PCM tables reproduce exactly")
    else:
        path.write_text(content())
